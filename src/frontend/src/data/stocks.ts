export const getStockById = (id: string): Stock | undefined =>
  stocks.find((s) => s.id === id);

export const getTopGainers = (n = 5): Stock[] =>
  [...stocks].sort((a, b) => b.changePercent - a.changePercent).slice(0, n);

export const getTopLosers = (n = 5): Stock[] =>
  [...stocks].sort((a, b) => a.changePercent - b.changePercent).slice(0, n);

export function generatePriceHistory(
  stock: Stock,
  days = 30,
): { date: string; price: number }[] {
  const history: { date: string; price: number }[] = [];
  let price = stock.low52w + (stock.currentPrice - stock.low52w) * 0.4;
  const seed = stock.ticker.charCodeAt(0);
  for (let i = days; i >= 0; i--) {
    const d = new Date();
    d.setDate(d.getDate() - i);
    const rand = Math.sin(seed * i * 0.7) * 0.015 + Math.cos(i * 0.3) * 0.01;
    price = price * (1 + rand);
    if (i === 0) price = stock.currentPrice;
    history.push({
      date: d.toLocaleDateString("en-IN", { month: "short", day: "numeric" }),
      price: Number.parseFloat(price.toFixed(2)),
    });
  }
  return history;
}
