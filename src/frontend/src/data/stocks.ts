export interface Stock {
  id: string;
  name: string;
  ticker: string;
  sector: string;
  currentPrice: number;
  previousClose: number;
  change: number;
  changePercent: number;
  marketCap: string;
  volume: string;
  pe: number;
  high52w: number;
  low52w: number;
  dividendYield: number;
  description: string;
}

function makeStock(
  id: string,
  name: string,
  ticker: string,
  sector: string,
  currentPrice: number,
  prevDelta: number,
  marketCap: string,
  volume: string,
  pe: number,
  dividendYield: number,
  description: string,
): Stock {
  const previousClose = Number.parseFloat(
    (currentPrice * (1 - prevDelta / 100)).toFixed(2),
  );
  const change = Number.parseFloat((currentPrice - previousClose).toFixed(2));
  const changePercent = Number.parseFloat(
    ((change / previousClose) * 100).toFixed(2),
  );
  return {
    id,
    name,
    ticker,
    sector,
    currentPrice,
    previousClose,
    change,
    changePercent,
    marketCap,
    volume,
    pe,
    high52w: Number.parseFloat((currentPrice * 1.35).toFixed(2)),
    low52w: Number.parseFloat((currentPrice * 0.65).toFixed(2)),
    dividendYield,
    description,
  };
}

